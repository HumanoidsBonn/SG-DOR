
import numpy as np
import torch
from torch.utils.data import Dataset
import glob
import os

class PepperPointDataset(Dataset):
    def __init__(self, data_root, split='train', npoints=32768, augment=True, use_bg=False, use_color=False, 
                 shoot_mode='merge', color_dropout_rate=0.20, return_proposals_gt=False, use_4mm=True,
                 pos_jitter=0.002, color_jitter=True):
        """
        Args:
            data_root (str): Path to data folder containing .npz files
            split (str): 'train', 'val', or 'test'
            npoints (int): Number of points to sample (default 32k for thin instance survival)
            augment (bool): Whether to apply data augmentation (enforced for 'train' only)
            use_bg (bool): If True, leaves ID 0 as background. If False, maps 1-5 to 0-4.
            use_color (bool): If True, loads and normalizes RGB from [0,255] to [0,1]
            shoot_mode (str): 'merge' (ID 5 -> Leaf), 'drop' (discard 5), or 'keep' (stay as 5)
            color_dropout_rate (float): Probability of an instance being dropped to grey (Weak-Signal)
            return_proposals_gt (bool): If True, returns variable-sized GT centers/extents.
            use_4mm (bool): If True, looks for *_4mm.npz files generated by audit script.
        """
        self.npoints = npoints
        self.split = split
        self.use_bg = use_bg
        self.use_color = use_color
        self.shoot_mode = shoot_mode
        self.color_dropout_rate = color_dropout_rate
        self.return_proposals_gt = return_proposals_gt
        self.augment = augment if split == 'train' else False
        self.use_4mm = use_4mm
        self.pos_jitter = pos_jitter
        self.color_jitter = color_jitter
        
        # Get all files (Check for 4mm first)
        suffix = "_4mm.npz" if use_4mm else "_pc.npz"
        all_files = sorted(glob.glob(os.path.join(data_root, "**/*" + suffix), recursive=True))
        
        if len(all_files) == 0:
            print(f"[WARNING] No {suffix} files found in {data_root}. Trying fallback to *_pc.npz")
            all_files = sorted(glob.glob(os.path.join(data_root, "**/*_pc.npz"), recursive=True))
            
        if len(all_files) == 0:
            raise ValueError(f"No .npz files found in {data_root}")

        # Local RNG for split permutation
        rng = np.random.default_rng(42)
        perm = rng.permutation(len(all_files))
        
        # 80-10-10 split
        n_train = int(len(all_files) * 0.8)
        n_val = int(len(all_files) * 0.1)
        
        if split == 'train':
            indices = perm[:n_train]
        elif split == 'val':
            indices = perm[n_train:n_train+n_val]
        elif split == 'test':
            indices = perm[n_train+n_val:]
        else:
            indices = perm # 'all'
            
        self.file_list = [all_files[i] for i in indices]
        print(f"[{split}] Loading {len(self.file_list)} scenes (Augment: {self.augment}, UseBG: {use_bg}, Shoot: {shoot_mode})")

    def __len__(self):
        return len(self.file_list)

    def __getitem__(self, idx):
        file_path = self.file_list[idx]
        data = np.load(file_path, mmap_mode='r')
        
        raw_points = data['points']
        raw_semantics = data['semantics'].astype(np.int64)
        raw_normals = data['normals']
        raw_instances = data['instances']
        
        # 1. Shoot Mode Handling (ID 5: Shoot)
        # ID Mapping: 1:Stem, 2:Leaf, 3:Peduncle, 4:Fruit, 5:Shoot
        valid_mask = np.ones(len(raw_semantics), dtype=bool)
        
        if self.shoot_mode == 'merge':
            raw_semantics[raw_semantics == 5] = 2 # Shoot -> Leaf
        elif self.shoot_mode == 'drop':
            valid_mask[raw_semantics == 5] = False
        # else: 'keep' -> stays as 5

        # 2. Class-Stratified Sampling Budget
        # Budgets (Total 16k): Stem:3k, Leaf:6k, Ped:3k, Fruit:4k
        budgets = {1: 3000, 2: 6000, 3: 3000, 4: 4000}
        
        sampled_indices = []
        
        # Track indices we used for budgets to avoid duplication in top-up
        budget_indices_set = set()

        for class_id, budget in budgets.items():
            class_mask = (raw_semantics == class_id) & valid_mask
            class_idxs = np.where(class_mask)[0]
            num_found = len(class_idxs)
            
            if num_found == 0:
                continue
                
            if num_found > budget:
                # [STRATEGY] User requested FPS. Since data is already 4mm voxelized, 
                # random selection is spatially uniform enough, but we'll use a simple
                # stride or shuffle for speed.
                np.random.shuffle(class_idxs)
                selected = class_idxs[:budget]
            else:
                selected = class_idxs
                
            sampled_indices.extend(selected)
            budget_indices_set.update(selected)

        # 3. Top-up from Full Set (Context)
        current_count = len(sampled_indices)
        if current_count < self.npoints:
            remaining = self.npoints - current_count
            
            # Available for top-up: anything in valid_mask
            all_valid_idxs = np.where(valid_mask)[0]
            
            if len(all_valid_idxs) > 0:
                # [OPTIONAL] Exclude points already in budget_indices? 
                # If we allow duplicates, it's safer for small scenes.
                # If we want unique points, we filter.
                # Let's allowing duplicates (replace=True) to guarantee npoints
                fill_idxs = np.random.choice(all_valid_idxs, remaining, replace=True)
                sampled_indices.extend(fill_idxs)
        
        # Final selection
        choice = np.array(sampled_indices)
        if len(choice) > self.npoints:
             choice = choice[:self.npoints]
        np.random.shuffle(choice)

        # Pull only sampled points to memory
        points = np.array(raw_points[choice])
        semantics = np.array(raw_semantics[choice])
        normals = np.array(raw_normals[choice])
        instances = np.array(raw_instances[choice])
        
        # 2. Add Colors if requested
        if self.use_color:
            raw_colors = data['colors']
            colors = np.array(raw_colors[choice]).astype(np.float32) / 255.0
        
        # 3. Center coordinates
        centroid = np.mean(points, axis=0)
        points = points - centroid

        # 4. Augmentation (Train only)
        if self.augment:
            # A. Rotation around Z
            theta = np.random.uniform(0, 2*np.pi)
            cos_t = np.cos(theta)
            sin_t = np.sin(theta)
            R = np.array([
                [cos_t, -sin_t, 0],
                [sin_t,  cos_t, 0],
                [0,      0,     1]
            ])
            points = np.dot(points, R.T)
            normals = np.dot(normals, R.T)
            
            # B. Jitter (Spatial only)
            if self.pos_jitter > 0:
                noise = np.random.normal(0, self.pos_jitter, size=points.shape)
                points += noise
            
            # C. Scale
            scale = np.random.uniform(0.9, 1.1)
            points *= scale

            # D. Random Point Removal
            dropout_ratio = np.random.uniform(0, 0.3)
            n_drop = int(self.npoints * dropout_ratio)
            if n_drop > 0:
                keep_idx = np.random.choice(self.npoints, self.npoints - n_drop, replace=False)
                fill_idx = np.random.choice(keep_idx, n_drop, replace=True)
                final_idx = np.concatenate([keep_idx, fill_idx])
                np.random.shuffle(final_idx)
                
                points = points[final_idx]
                normals = normals[final_idx]
                semantics = semantics[final_idx]
                instances = instances[final_idx]
                if self.use_color:
                    colors = colors[final_idx]

            # E. Weak-Signal Color Augmentation (Heavy Noise)
            if self.use_color and self.color_jitter:
                # 1. Segment-level Dropout (color_dropout_rate of instances to grey)
                u_instances = np.unique(instances)
                for inst in u_instances:
                    if np.random.random() < self.color_dropout_rate:
                        mask = (instances == inst)
                        colors[mask] = 0.5 # Neutral Grey
                
                # 2. HSV Jitter (Approximate with RGB manipulation for speed)
                # Global brightness/contrast
                brightness = np.random.uniform(0.7, 1.3)
                colors = np.clip(colors * brightness, 0, 1)
                
                contrast = np.random.uniform(0.7, 1.3)
                colors = np.clip((colors - 0.5) * contrast + 0.5, 0, 1)
                
                # Per-point RGB Jitter
                noise = np.random.normal(0, 0.02, size=colors.shape)
                colors = np.clip(colors + noise, 0, 1)

        # 5. Normalize Normals to unit length (Robustness)
        norm_mags = np.linalg.norm(normals, axis=1, keepdims=True)
        normals = np.divide(normals, norm_mags, out=normals, where=norm_mags > 1e-8)

        # 6. Map Labels
        # Convert to signed int64 before subtraction to avoid uint8 underflow (255)
        semantics = semantics.astype(np.int64)

        # Subtraction to handle 0-based indexing further down
        
        # If use_bg is True, we keep IDs 1-5 as they are (background is ID 0)
        # We assume the model is configured with 6 classes.
        # If use_bg is False, we map 1-5 -> 0-4 (standard 5-class model)
        if not self.use_bg:
             # Mask background points (0) to a valid class (e.g. Stem/0) 
             # Or better: ensure background points don't exist in generated scenes
             # The generatedScenes currently use 1-5. ID 0 is usually an empty voxel.
             semantics = semantics - 1
             semantics[semantics < 0] = 0 # Clamp any 0 (background) to 0 (stem)
        
        if self.use_color:
            input_features = np.concatenate([points, normals, colors], axis=1)
        else:
            input_features = np.concatenate([points, normals], axis=1)

        # 7. Generate Multi-Head GT (Offsets and Extents)
        # We calculate these on-the-fly from the point cloud to ensure they match the sampled points
        offsets = np.zeros((self.npoints, 3), dtype=np.float32)
        extents = np.zeros((self.npoints, 3), dtype=np.float32)
        
        # Find unique instances (excluding background 0 if it exists)
        unique_insts = np.unique(instances)
        
        gt_centers_list = []
        gt_extents_list = []
        gt_classes_list = []
        
        # A) Handle Non-Stem Instances (Leaf, Peduncle, Fruit)
        # We iterate instances to compute offsets/extents for the whole cloud
        for inst_id in unique_insts:
            if inst_id == -1: continue # Skip invalid
            if inst_id == 0 and not self.use_bg: pass # If 0 is background, skip. But if 0 is an instance ID? 
            # In our generation, instance IDs are > 0.
            if inst_id == 0: continue

            mask = (instances == inst_id)
            inst_xyz = points[mask]
            
            # Target 1: Absolute Offset to Centroid (Meters)
            centroid = np.mean(inst_xyz, axis=0)
            offsets[mask] = centroid - inst_xyz
            
            # Target 2: Log-AABB Extents (ln(meters))
            mins = np.min(inst_xyz, axis=0)
            maxs = np.max(inst_xyz, axis=0)
            inst_extent = maxs - mins
            extents[mask] = np.log(inst_extent + 1e-3)
            
            # Target 3: Scene-level GT for Proposals
            if self.return_proposals_gt:
                # Identify Class
                # We assume instance purity (mostly true)
                inst_sem = semantics[mask][0]
                
                # Skip Stem (0) here, handled separately via segmentation
                if inst_sem == 0:
                    continue
                    
                gt_centers_list.append(centroid)
                gt_extents_list.append(inst_extent)
                gt_classes_list.append(inst_sem)

        # B) Handle Stem (Class 0) via Segmentation
        if self.return_proposals_gt:
            # We pass the full scene points/sem/inst masked to Stems
            # Ideally we pass all points but tell it to look for class 0
            from pepper_scene_graphs.training.gt_helpers import build_stem_segment_targets
            
            # Convert to torch for helper (it expects torch usually, but let's check helper)
            # Helper uses torch.cdist, fps. So needs torch tensors.
            t_xyz = torch.from_numpy(points).float()
            t_sem = torch.from_numpy(semantics).long()
            t_inst = torch.from_numpy(instances.astype(np.int32)).long()
            
            # Run Stem Segmentation
            # Using CPU or GPU? DataLoader is usually CPU. 
            # torch fps on CPU is fine for 4096 points.
            stem_centers, stem_extents = build_stem_segment_targets(
                t_xyz, t_sem, t_inst, stem_class_id=0, k_seg=6
            )
            
            if len(stem_centers) > 0:
                # Convert back to numpy list
                for fc, fe in zip(stem_centers.numpy(), stem_extents.numpy()):
                    gt_centers_list.append(fc)
                    gt_extents_list.append(fe)
                    gt_classes_list.append(0) # Class 0 for Stem

        ret_dict = {
            'x': torch.from_numpy(input_features).float(),
            'y_sem': torch.from_numpy(semantics).long(),
            'y_off': torch.from_numpy(offsets).float(),
            'y_ext': torch.from_numpy(extents).float(),
            'instances': torch.from_numpy(instances.astype(np.int32)).long()
        }
        
        if self.return_proposals_gt:
            # Pad to fixed size
            MAX_GT_PROPOSALS = 512 
            
            gt_centers = torch.zeros((MAX_GT_PROPOSALS, 3), dtype=torch.float32)
            gt_extents = torch.zeros((MAX_GT_PROPOSALS, 3), dtype=torch.float32)
            gt_classes = torch.zeros((MAX_GT_PROPOSALS), dtype=torch.long) 
            gt_mask = torch.zeros((MAX_GT_PROPOSALS), dtype=torch.float32) 
            
            num_actual = len(gt_centers_list)
            if num_actual > 0:
                # Convert list of arrays/tensors to single tensor
                # stem_centers are tensors, others are arrays. Convert all to tensors.
                all_centers = torch.stack([torch.as_tensor(x) for x in gt_centers_list])
                all_extents = torch.stack([torch.as_tensor(x) for x in gt_extents_list])
                all_classes = torch.tensor(gt_classes_list, dtype=torch.long)
                
                # Shuffle before truncation
                indices = torch.randperm(num_actual)
                if num_actual > MAX_GT_PROPOSALS:
                    indices = indices[:MAX_GT_PROPOSALS]
                    num_actual = MAX_GT_PROPOSALS
                
                gt_centers[:num_actual] = all_centers[indices]
                gt_extents[:num_actual] = all_extents[indices]
                gt_classes[:num_actual] = all_classes[indices]
                gt_mask[:num_actual] = 1.0

            ret_dict['gt_prop_center'] = gt_centers
            ret_dict['gt_prop_extent'] = gt_extents
            ret_dict['gt_prop_class'] = gt_classes
            ret_dict['gt_prop_mask'] = gt_mask
        
        return ret_dict
